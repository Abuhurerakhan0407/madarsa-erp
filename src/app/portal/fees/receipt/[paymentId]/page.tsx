import { notFound } from "next/navigation";
import { getPortalGuardianFees } from "@/lib/portal/fees";
import { resolvePortalLocale } from "@/lib/portal/locale";

const money = (value: number) => new Intl.NumberFormat("en-IN", {
  style: "currency",
  currency: "INR",
  maximumFractionDigits: 2
}).format(value);

const copy = {
  en: { title: "Fee payment receipt", student: "Student", fee: "Fee", amount: "Amount paid", date: "Payment date", mode: "Payment method", receipt: "Receipt number", note: "Note" },
  ur: { title: "فیس ادائیگی رسید", student: "طالب علم", fee: "فیس", amount: "ادا شدہ رقم", date: "ادائیگی کی تاریخ", mode: "ادائیگی کا طریقہ", receipt: "رسید نمبر", note: "نوٹ" }
} as const;

export default async function PortalFeeReceiptPage({
  params,
  searchParams
}: {
  params: Promise<{ paymentId: string }>;
  searchParams: Promise<{ tenant?: string | string[]; locale?: string | string[] }>;
}) {
  const { paymentId: rawPaymentId } = await params;
  const query = await searchParams;
  const tenantId = Number(typeof query.tenant === "string" ? query.tenant : "");
  const locale = resolvePortalLocale(typeof query.locale === "string" ? query.locale : null);
  const paymentId = Number(rawPaymentId);
  if (!Number.isInteger(tenantId) || tenantId <= 0 || !Number.isInteger(paymentId) || paymentId <= 0) notFound();

  const rows = await getPortalGuardianFees(tenantId);
  let found: null | {
    studentName: string;
    studentNumber: string;
    feeName: string;
    amount: number;
    date: string;
    mode: string;
    receipt: string;
    note: string;
  } = null;

  for (const row of rows) {
    const payment = row.payments.find((item) => item.id === paymentId);
    if (!payment) continue;
    found = {
      studentName: row.studentName,
      studentNumber: row.studentNumber,
      feeName: row.feeName,
      amount: payment.amount,
      date: payment.paymentDate,
      mode: payment.mode,
      receipt: payment.receiptNumber,
      note: payment.note
    };
    break;
  }
  if (!found) notFound();

  const t = copy[locale];
  return <main dir={locale === "ur" ? "rtl" : "ltr"} style={{ maxWidth: 720, margin: "0 auto", padding: "32px 24px", fontFamily: "system-ui,sans-serif" }}>
    <header style={{ borderBottom: "2px solid currentColor", paddingBottom: 16, marginBottom: 24 }}>
      <p style={{ margin: 0, opacity: .7 }}>Ilmgaah</p>
      <h1>{t.title}</h1>
    </header>
    <section style={{ display: "grid", gridTemplateColumns: "repeat(2,minmax(0,1fr))", gap: 16 }}>
      <p>{t.student}<br/><strong>{found.studentName} · {found.studentNumber}</strong></p>
      <p>{t.fee}<br/><strong>{found.feeName}</strong></p>
      <p>{t.amount}<br/><strong>{money(found.amount)}</strong></p>
      <p>{t.date}<br/><strong>{found.date}</strong></p>
      <p>{t.mode}<br/><strong>{found.mode}</strong></p>
      <p>{t.receipt}<br/><strong>{found.receipt}</strong></p>
    </section>
    {found.note ? <p><strong>{t.note}:</strong> {found.note}</p> : null}
    <p style={{ marginTop: 40, fontSize: 12, opacity: .65 }}>Generated by Ilmgaah. Use your browser print command to print or save this receipt.</p>
  </main>;
}
