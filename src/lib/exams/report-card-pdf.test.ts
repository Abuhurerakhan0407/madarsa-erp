import {describe,expect,it} from 'vitest';
import {createReportCardPdf,createUnicodeReportCardPdf} from './report-card-pdf';
import type {ExamReportCard} from './workspace';

const card:ExamReportCard={
 student:{personId:1,name:'Ayaan Khan',nameNative:null,studentNumber:'ST-001'},
 exam:{id:1,labels:{en:'Term 1'},state:'results_published',startsOn:'2026-09-01',endsOn:'2026-09-10',sessionId:7,sessionLabel:'2026-27'},
 result:{snapshotId:1,percentage:88.5,aggregateStatus:'pass',gradeKey:'A',rankValue:1,promotionRecommendation:'promote',publishedAt:'2026-09-11T08:30:00Z'},
 subjects:[{subjectName:'Qur’an',labels:{en:'Qur’an'},rawMarks:88.5,maximumMarks:100,outcome:'pass',gradeKey:'A'}],
 issue:{id:1,revision:2,templateKey:'standard_report_card',issuedAt:'2026-09-11T08:30:00Z',verificationCode:'VERIFY-123'}
};

describe('exam report card PDF',()=>{
 it('uses the shared Ilmgaah document template and readable published-result values',()=>{
  const pdf=createReportCardPdf(card,{institutionName:'Ilmgaah Academy',branchName:'Main Branch'});
  const text=new TextDecoder().decode(pdf);
  expect(text).toContain('%ILMGAAH');
  expect(text).toContain('Student Report Card');
  expect(text).toContain("Qur'an");
  expect(text).toContain('88.5%');
  expect(text).toContain('2026-27');
  expect(text).toContain('ST-001');
  expect(text).toContain('88.5/100');
  expect(text).toContain('Grade A');
  expect(text).toContain('VERIFY-123');
  expect(text).toContain('11 Sep 2026');
  expect(text).toContain('Generated by Ilmgaah');
  expect(text).not.toContain('Madarsa ERP');
  expect(text).not.toContain('-%');
 });
 it('paginates long report cards without truncating subject rows',()=>{
  const subjects=Array.from({length:30},(_,index)=>({subjectName:`Subject ${index+1}`,labels:{en:`Subject ${index+1}`},rawMarks:70+index%20,maximumMarks:100,outcome:'pass',gradeKey:'B'}));
  const pdf=createReportCardPdf({...card,subjects},{institutionName:'Ilmgaah Academy',branchName:'Main Branch'});const text=new TextDecoder().decode(pdf);
  expect(text.match(/\/Type \/Page\b/g)?.length).toBe(3);expect(text).toContain('Subject 1');expect(text).toContain('Subject 30');expect(text).not.toContain('+ 16 more records');
 });
 it('renders a Unicode PDF when actual Urdu payload fields are present',async()=>{
  const urduCard:ExamReportCard={...card,student:{...card.student,nameNative:'ایان خان'},exam:{...card.exam,labels:{...card.exam.labels,ur:'پہلی سہ ماہی'}},subjects:card.subjects.map(subject=>({...subject,labels:{...subject.labels,ur:'قرآن'}}))};
  const pdf=await createUnicodeReportCardPdf(urduCard,{institutionName:'Ilmgaah Academy',branchName:'Main Branch'},'ur');
  expect(pdf.byteLength).toBeGreaterThan(1000);
  expect(new TextDecoder().decode(pdf.slice(0,32))).toContain('%ILMGAAH');
 });
});
