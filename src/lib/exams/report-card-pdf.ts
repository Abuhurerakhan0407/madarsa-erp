import { createSimplePdf, type PdfTextLine } from "@/lib/documents/simple-pdf";
import type { ExamReportCard } from "./workspace";

function englishLabel(labels: { en?: string }, fallback: string): string {
  return labels.en?.trim() || fallback;
}

function value(value: string | number | null | undefined): string {
  return value === null || value === undefined || value === "" ? "-" : String(value);
}

export function createReportCardPdf(card: ExamReportCard, context: { institutionName: string; branchName: string }): Uint8Array {
  const examName = englishLabel(card.exam.labels, "Published exam");
  const lines: PdfTextLine[] = [
    { text: context.institutionName, size: 15, bold: true },
    { text: context.branchName, size: 10, gapAfter: 8 },
    { text: `Student: ${card.student.name}`, size: 12, bold: true },
    { text: `Student ID: ${card.student.studentNumber}` },
    { text: `Exam: ${examName}` },
    { text: `Exam window: ${card.exam.startsOn} to ${card.exam.endsOn}` },
    { text: `Result: ${value(card.result.percentage)}% | Grade: ${value(card.result.gradeKey)} | Outcome: ${card.result.aggregateStatus}`, gapAfter: 10 },
    { text: "Subjects", size: 12, bold: true }
  ];

  for (const subject of card.subjects) {
    lines.push({
      text: `${englishLabel(subject.labels, subject.subjectName)} | Marks ${value(subject.rawMarks)}/${subject.maximumMarks} | Grade ${value(subject.gradeKey)} | ${subject.outcome}`
    });
  }

  lines.push(
    { text: "", gapAfter: 4 },
    { text: `Promotion recommendation: ${card.result.promotionRecommendation}`, bold: true },
    { text: `Published: ${value(card.result.publishedAt)}` },
    { text: `Verification code: ${card.issue?.verificationCode || "-"}`, bold: true },
    { text: `Issue revision: ${card.issue?.revision ?? 1}` },
    { text: "Generated by Madarsa ERP from the governed published result record.", size: 8, gapAfter: 0 }
  );

  return createSimplePdf({ title: "Student Report Card", lines });
}
