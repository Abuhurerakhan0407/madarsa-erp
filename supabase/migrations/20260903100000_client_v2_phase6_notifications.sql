create or replace function private.emit_client_v2_in_app_v1(
  p_tenant_id bigint,
  p_event_key text,
  p_aggregate_type text,
  p_aggregate_id text,
  p_payload jsonb,
  p_recipient_identity_ids uuid[]
) returns bigint
language plpgsql
security definer
set search_path to ''
as $fn$
declare
  v_event_id bigint;
  v_policy_id bigint;
  v_template_id bigint;
  v_identity uuid;
  v_resolution_id bigint;
  v_event_key text:=lower(btrim(coalesce(p_event_key,'')));
  v_aggregate_type text:=lower(btrim(coalesce(p_aggregate_type,'')));
  v_aggregate_id text:=btrim(coalesce(p_aggregate_id,''));
  v_payload jsonb:=coalesce(p_payload,'{}'::jsonb);
  v_event_idempotency text;
  v_dispatch_idempotency text;
  v_payload_digest text;
begin
  if p_tenant_id is null or v_event_key='' or v_aggregate_type='' or v_aggregate_id='' then
    raise exception 'notification event identity is incomplete';
  end if;
  if coalesce(array_length(p_recipient_identity_ids,1),0)=0 then return null; end if;
  if coalesce(v_payload->>'priority','normal') not in ('normal','important','urgent') then
    v_payload:=jsonb_set(v_payload,'{priority}','"normal"'::jsonb,true);
  end if;
  v_event_idempotency:='client-v2:'||v_event_key||':'||v_aggregate_type||':'||v_aggregate_id;
  v_payload_digest:=pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_payload::text,'UTF8'),'sha256'),'hex');

  insert into public.domain_notification_events(
    tenant_id,event_key,aggregate_type,aggregate_id,payload,payload_digest,occurred_at,idempotency_key
  ) values(
    p_tenant_id,v_event_key,v_aggregate_type,v_aggregate_id,v_payload,v_payload_digest,clock_timestamp(),v_event_idempotency
  ) on conflict(tenant_id,idempotency_key) do update set payload=excluded.payload,payload_digest=excluded.payload_digest
  returning id into v_event_id;

  insert into public.notification_policies(
    tenant_id,event_key,version,channels,audience_rules,consent_basis,quiet_hours,retry_policy,state,published_at
  ) values(
    p_tenant_id,v_event_key,1,array['in_app']::text[],
    jsonb_build_object('resolver','verified_portal_identity'),
    jsonb_build_object('in_app','verified_portal_link'),
    '{}'::jsonb,jsonb_build_object('max_attempts',1),'published',clock_timestamp()
  ) on conflict(tenant_id,event_key,version) do update set
    channels=excluded.channels,audience_rules=excluded.audience_rules,consent_basis=excluded.consent_basis,
    state='published',published_at=coalesce(public.notification_policies.published_at,excluded.published_at)
  returning id into v_policy_id;

  insert into public.notification_templates(
    tenant_id,policy_id,channel,locale,subject_template,body_template,required_variables,state,validation_result,published_at
  ) values(
    p_tenant_id,v_policy_id,'in_app','en','{{title}}','{{body}}',array['title','body']::text[],
    'published',jsonb_build_object('valid',true,'validated_by','client-v2-phase6'),clock_timestamp()
  ) on conflict(tenant_id,policy_id,channel,locale) do update set
    subject_template=excluded.subject_template,body_template=excluded.body_template,
    required_variables=excluded.required_variables,state='published',validation_result=excluded.validation_result,
    published_at=coalesce(public.notification_templates.published_at,excluded.published_at)
  returning id into v_template_id;

  for v_identity in
    select distinct x from unnest(p_recipient_identity_ids) x where x is not null
  loop
    if not exists(
      select 1 from public.identity_person_links l
      where l.tenant_id=p_tenant_id and l.identity_id=v_identity and l.status='verified'
    ) then continue; end if;

    insert into public.notification_recipient_resolutions(
      tenant_id,event_id,recipient_identity_id,relationship_evidence,locale,channels,consent_snapshot
    ) values(
      p_tenant_id,v_event_id,v_identity,jsonb_build_object('basis','verified_portal_link'),'en',array['in_app']::text[],
      jsonb_build_object('in_app','allowed')
    ) on conflict(tenant_id,event_id,recipient_identity_id) do update set resolved_at=clock_timestamp()
    returning id into v_resolution_id;

    v_dispatch_idempotency:='client-v2:in-app:'||v_event_id::text||':'||v_identity::text;
    insert into public.notification_dispatches(
      tenant_id,event_id,recipient_resolution_id,template_id,channel,destination_hash,rendered_digest,state,
      idempotency_key,sent_at
    ) values(
      p_tenant_id,v_event_id,v_resolution_id,v_template_id,'in_app',
      pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_identity::text,'UTF8'),'sha256'),'hex'),
      pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_payload::text||':'||v_identity::text,'UTF8'),'sha256'),'hex'),
      'delivered',v_dispatch_idempotency,clock_timestamp()
    ) on conflict(tenant_id,idempotency_key) do nothing;
  end loop;
  return v_event_id;
end;
$fn$;

create or replace function public.get_portal_notification_center_v1(
  p_identity_id uuid,p_tenant_id bigint,p_limit integer default 50
) returns jsonb
language plpgsql stable
security definer
set search_path to ''
as $fn$
declare v_items jsonb;v_unread integer;v_limit integer:=least(100,greatest(1,coalesce(p_limit,50)));begin
  if not exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified') then
    raise exception 'verified portal link required';
  end if;
  select count(*)::int into v_unread
  from public.notification_dispatches d
  join public.notification_recipient_resolutions r on r.tenant_id=d.tenant_id and r.id=d.recipient_resolution_id
  where d.tenant_id=p_tenant_id and r.recipient_identity_id=p_identity_id and d.channel='in_app'
    and d.state not in('read','cancelled');

  select coalesce(jsonb_agg(row_to_json(x) order by x.sent_at desc,x.id desc),'[]'::jsonb) into v_items
  from (
    select d.id,d.event_id,e.event_key,
      case when e.payload->>'priority' in('normal','important','urgent') then e.payload->>'priority' else 'normal' end priority,
      coalesce(nullif(e.payload->>'source_module',''),'Institution') source_module,
      e.payload->'title' title,e.payload->'body' body,
      nullif(e.payload->>'link','') link,
      coalesce(d.sent_at,d.created_at) sent_at,
      (d.state='read') is_read,
      d.state
    from public.notification_dispatches d
    join public.notification_recipient_resolutions r on r.tenant_id=d.tenant_id and r.id=d.recipient_resolution_id
    join public.domain_notification_events e on e.tenant_id=d.tenant_id and e.id=d.event_id
    where d.tenant_id=p_tenant_id and r.recipient_identity_id=p_identity_id and d.channel='in_app' and d.state<>'cancelled'
    order by coalesce(d.sent_at,d.created_at) desc,d.id desc
    limit v_limit
  ) x;
  return jsonb_build_object('unread_count',v_unread,'items',v_items);
end;$fn$;

create or replace function public.mark_portal_notification_read_v1(
  p_identity_id uuid,p_tenant_id bigint,p_dispatch_id bigint
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
begin
  update public.notification_dispatches d set state='read'
  from public.notification_recipient_resolutions r
  where d.tenant_id=p_tenant_id and d.id=p_dispatch_id and d.channel='in_app'
    and r.tenant_id=d.tenant_id and r.id=d.recipient_resolution_id and r.recipient_identity_id=p_identity_id
    and exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified');
  if not found then raise exception 'portal notification is unavailable'; end if;
  return jsonb_build_object('dispatch_id',p_dispatch_id,'read',true);
end;$fn$;

create or replace function public.upsert_portal_push_subscription_v1(
  p_identity_id uuid,p_tenant_id bigint,p_subscription jsonb,p_device_label text default null
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
declare v_endpoint text;v_hash text;v_id bigint;begin
  if not exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified') then raise exception 'verified portal link required';end if;
  if p_subscription is null or jsonb_typeof(p_subscription)<>'object' then raise exception 'push subscription object required';end if;
  v_endpoint:=nullif(btrim(coalesce(p_subscription->>'endpoint','')),'');
  if v_endpoint is null or length(v_endpoint)>2048 then raise exception 'valid push endpoint required';end if;
  if nullif(p_subscription#>>'{keys,p256dh}','') is null or nullif(p_subscription#>>'{keys,auth}','') is null then raise exception 'push subscription keys required';end if;
  v_hash:=pg_catalog.encode(extensions.digest(pg_catalog.convert_to(v_endpoint,'UTF8'),'sha256'),'hex');
  insert into public.portal_push_subscriptions(tenant_id,identity_id,endpoint_hash,subscription,device_label,state,updated_at,revoked_at)
  values(p_tenant_id,p_identity_id,v_hash,p_subscription,nullif(btrim(coalesce(p_device_label,'')),''),'active',clock_timestamp(),null)
  on conflict(tenant_id,identity_id,endpoint_hash) do update set subscription=excluded.subscription,device_label=excluded.device_label,state='active',updated_at=clock_timestamp(),revoked_at=null
  returning id into v_id;
  return jsonb_build_object('subscription_id',v_id,'endpoint_hash',v_hash,'state','active');
end;$fn$;

create or replace function public.revoke_portal_push_subscription_v1(
  p_identity_id uuid,p_tenant_id bigint,p_endpoint_hash text
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
begin
  if p_endpoint_hash !~ '^[a-f0-9]{64}$' then raise exception 'valid endpoint hash required';end if;
  update public.portal_push_subscriptions set state='revoked',revoked_at=clock_timestamp(),updated_at=clock_timestamp()
  where tenant_id=p_tenant_id and identity_id=p_identity_id and endpoint_hash=p_endpoint_hash and state='active'
    and exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified');
  return jsonb_build_object('endpoint_hash',p_endpoint_hash,'revoked',found);
end;$fn$;

