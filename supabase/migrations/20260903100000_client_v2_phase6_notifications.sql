create or replace function public.publish_portal_notice_v2(
  p_identity_id uuid,p_tenant_id bigint,p_branch_id bigint,p_audience_type text,p_labels jsonb,p_body jsonb,p_priority text,p_expires_at timestamptz
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
declare v_membership bigint;v_audience text:=lower(btrim(coalesce(p_audience_type,'')));v_priority text:=lower(btrim(coalesce(p_priority,'normal')));v_id bigint;begin
  v_membership:=public.resolve_portal_operator_membership_v1(p_identity_id,p_tenant_id,p_branch_id);
  if v_membership is null then raise exception 'portal administration permission denied';end if;
  if v_audience not in('tenant','parents','employees') then raise exception 'portal notice audience must be tenant, parents, or employees';end if;
  if v_priority not in('normal','important','urgent') then raise exception 'portal notice priority is invalid';end if;
  if p_labels is null or jsonb_typeof(p_labels)<>'object' or nullif(btrim(coalesce(p_labels->>'en','')),'') is null then raise exception 'English notice title required';end if;
  if p_body is null or jsonb_typeof(p_body)<>'object' or nullif(btrim(coalesce(p_body->>'en','')),'') is null then raise exception 'English notice body required';end if;
  if p_expires_at is not null and p_expires_at<=now() then raise exception 'notice expiry must be in the future';end if;
  insert into public.portal_notices(tenant_id,branch_id,audience_type,audience_key,labels,body,priority,state,published_at,expires_at,published_by_membership_id)
  values(p_tenant_id,p_branch_id,v_audience,null,p_labels,p_body,v_priority,'published',clock_timestamp(),p_expires_at,v_membership) returning id into v_id;
  return jsonb_build_object('notice_id',v_id,'state','published','audience_type',v_audience,'priority',v_priority);
