begin;

alter table public.programs
  add column if not exists descriptions jsonb not null default '{}'::jsonb,
  add column if not exists template_key text not null default 'blank_custom';

alter table public.programs
  drop constraint if exists programs_template_key_check;
alter table public.programs
  add constraint programs_template_key_check check (
    template_key in (
      'hifz','nazra','amma_para','deeniyat','kitab','dars_e_nizami','general_academic','blank_custom'
    )
  );

update public.programs
set template_key = case program_type
  when 'hifz' then 'hifz'
  when 'nazra' then 'nazra'
  when 'dars_e_nizami' then 'dars_e_nizami'
  else template_key
end
where template_key = 'blank_custom';

alter table public.curriculum_version_items
  add column if not exists progress_method text not null default 'completion',
  add column if not exists unit_structure text not null default 'lesson';

alter table public.curriculum_version_items
  drop constraint if exists curriculum_version_items_progress_method_check;
alter table public.curriculum_version_items
  add constraint curriculum_version_items_progress_method_check check (
    progress_method in (
      'completion','percentage','rating','score','marks','memorization','range','checklist','rubric','pass_repeat','custom'
    )
  );

alter table public.curriculum_version_items
  drop constraint if exists curriculum_version_items_unit_structure_check;
alter table public.curriculum_version_items
  add constraint curriculum_version_items_unit_structure_check check (
    unit_structure in ('juz','surah','ayah_range','chapter','lesson','topic','book','custom_unit')
  );

create table if not exists public.curriculum_teaching_assignments (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete restrict,
  session_id bigint not null,
  program_id bigint not null,
  curriculum_item_id bigint not null,
  group_id bigint null,
  student_person_id bigint null,
  teacher_person_id bigint null,
  evaluation_method text not null default 'completion',
  status text not null default 'active',
  starts_on date not null default current_date,
  ends_on date null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint curriculum_teaching_assignments_tenant_id_id_key unique (tenant_id, id),
  constraint curriculum_teaching_assignments_tenant_session_fkey
    foreign key (tenant_id, session_id) references public.academic_sessions(tenant_id, id) on delete restrict,
  constraint curriculum_teaching_assignments_tenant_program_fkey
    foreign key (tenant_id, program_id) references public.programs(tenant_id, id) on delete restrict,
  constraint curriculum_teaching_assignments_tenant_item_fkey
    foreign key (tenant_id, curriculum_item_id) references public.curriculum_version_items(tenant_id, id) on delete restrict,
  constraint curriculum_teaching_assignments_tenant_group_fkey
    foreign key (tenant_id, group_id) references public.academic_groups(tenant_id, id) on delete restrict,
  constraint curriculum_teaching_assignments_tenant_student_fkey
    foreign key (tenant_id, student_person_id) references public.student_profiles(tenant_id, person_id) on delete restrict,
  constraint curriculum_teaching_assignments_tenant_teacher_fkey
    foreign key (tenant_id, teacher_person_id) references public.employee_profiles(tenant_id, person_id) on delete restrict,
  constraint curriculum_teaching_assignments_target_check
    check ((group_id is not null)::int + (student_person_id is not null)::int = 1),
  constraint curriculum_teaching_assignments_evaluation_method_check
    check (evaluation_method in ('completion','percentage','rating','score','marks','memorization','range','checklist','rubric','pass_repeat','custom')),
  constraint curriculum_teaching_assignments_status_check
    check (status in ('active','paused','completed','archived')),
  constraint curriculum_teaching_assignments_dates_check
    check (ends_on is null or ends_on >= starts_on)
);

create unique index if not exists curriculum_teaching_assignment_group_unique
  on public.curriculum_teaching_assignments (tenant_id, session_id, curriculum_item_id, group_id, coalesce(teacher_person_id, 0))
  where group_id is not null and status = 'active';

create unique index if not exists curriculum_teaching_assignment_student_unique
  on public.curriculum_teaching_assignments (tenant_id, session_id, curriculum_item_id, student_person_id, coalesce(teacher_person_id, 0))
  where student_person_id is not null and status = 'active';

create index if not exists curriculum_teaching_assignments_program_idx
  on public.curriculum_teaching_assignments (tenant_id, program_id, session_id, status);
create index if not exists curriculum_teaching_assignments_teacher_idx
  on public.curriculum_teaching_assignments (tenant_id, teacher_person_id, status)
  where teacher_person_id is not null;

create table if not exists public.student_curriculum_progress (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete restrict,
  student_person_id bigint not null,
  curriculum_unit_id bigint not null,
  teaching_assignment_id bigint null,
  teacher_person_id bigint null,
  progress_method text not null,
  state text not null default 'in_progress',
  progress_value jsonb not null default '{}'::jsonb,
  notes text null,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint student_curriculum_progress_tenant_student_fkey
    foreign key (tenant_id, student_person_id) references public.student_profiles(tenant_id, person_id) on delete restrict,
  constraint student_curriculum_progress_tenant_unit_fkey
    foreign key (tenant_id, curriculum_unit_id) references public.curriculum_units(tenant_id, id) on delete restrict,
  constraint student_curriculum_progress_tenant_assignment_fkey
    foreign key (tenant_id, teaching_assignment_id) references public.curriculum_teaching_assignments(tenant_id, id) on delete restrict,
  constraint student_curriculum_progress_tenant_teacher_fkey
    foreign key (tenant_id, teacher_person_id) references public.employee_profiles(tenant_id, person_id) on delete restrict,
  constraint student_curriculum_progress_method_check
    check (progress_method in ('completion','percentage','rating','score','marks','memorization','range','checklist','rubric','pass_repeat','custom')),
  constraint student_curriculum_progress_state_check
    check (state in ('not_started','in_progress','completed','passed','repeat','needs_support','skipped')),
  constraint student_curriculum_progress_notes_check
    check (notes is null or length(notes) <= 2000)
);

create index if not exists student_curriculum_progress_student_idx
  on public.student_curriculum_progress (tenant_id, student_person_id, occurred_at desc);
create index if not exists student_curriculum_progress_unit_idx
  on public.student_curriculum_progress (tenant_id, curriculum_unit_id, occurred_at desc);

insert into public.permissions(code, description)
values
  ('learning.progress.read', 'Read scoped student curriculum progress'),
  ('learning.progress.manage', 'Record scoped student curriculum progress')
on conflict (code) do update set description = excluded.description;

insert into public.role_permissions(tenant_id, role_id, permission_code)
select r.tenant_id, r.id, p.code
from public.roles r
cross join public.permissions p
where r.key = 'institution_owner'
  and r.status = 'active'
  and p.code in ('learning.progress.read','learning.progress.manage')
on conflict do nothing;

alter table public.curriculum_teaching_assignments enable row level security;
alter table public.student_curriculum_progress enable row level security;

revoke all on public.curriculum_teaching_assignments from anon;
revoke all on public.student_curriculum_progress from anon;

drop policy if exists curriculum_teaching_assignments_scoped_read on public.curriculum_teaching_assignments;
create policy curriculum_teaching_assignments_scoped_read
on public.curriculum_teaching_assignments
for select
to authenticated
using (private.has_permission(tenant_id, 'academics.structure.read', null));

drop policy if exists student_curriculum_progress_scoped_read on public.student_curriculum_progress;
create policy student_curriculum_progress_scoped_read
on public.student_curriculum_progress
for select
to authenticated
using (private.has_permission(tenant_id, 'learning.progress.read', null));

drop policy if exists curriculum_versions_structure_read on public.curriculum_versions;
create policy curriculum_versions_structure_read
on public.curriculum_versions
for select
to authenticated
using (private.has_permission(tenant_id, 'academics.structure.read', null));

drop policy if exists curriculum_items_structure_read on public.curriculum_version_items;
create policy curriculum_items_structure_read
on public.curriculum_version_items
for select
to authenticated
using (private.has_permission(tenant_id, 'academics.structure.read', null));

drop policy if exists curriculum_units_structure_read on public.curriculum_units;
create policy curriculum_units_structure_read
on public.curriculum_units
for select
to authenticated
using (private.has_permission(tenant_id, 'academics.structure.read', null));

grant select on public.curriculum_teaching_assignments to authenticated;
grant select on public.student_curriculum_progress to authenticated;
grant select, insert, update, delete on public.curriculum_teaching_assignments to service_role;
grant select, insert, update, delete on public.student_curriculum_progress to service_role;
grant usage, select on sequence public.curriculum_teaching_assignments_id_seq to service_role;
grant usage, select on sequence public.student_curriculum_progress_id_seq to service_role;

commit;
