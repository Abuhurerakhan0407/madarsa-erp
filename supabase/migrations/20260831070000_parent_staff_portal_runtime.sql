create table if not exists public.portal_access_codes(
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete restrict,
  branch_id bigint not null,
  person_id bigint not null,
  link_type text not null check(link_type in('guardian','employee')),
  token_digest text not null check(token_digest ~ '^[a-f0-9]{64}$'),
  state text not null default 'issued' check(state in('issued','claimed','revoked','expired')),
  expires_at timestamptz not null,
  issued_by_membership_id bigint not null,
  claimed_identity_id uuid references auth.users(id) on delete restrict,
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(token_digest),
  unique(tenant_id,id),
  foreign key(tenant_id,branch_id) references public.branches(tenant_id,id) on delete restrict,
  foreign key(tenant_id,person_id) references public.persons(tenant_id,id) on delete restrict,
  foreign key(tenant_id,issued_by_membership_id) references public.memberships(tenant_id,id) on delete restrict,
  check((state='claimed')=(claimed_identity_id is not null and claimed_at is not null))
);

create index if not exists portal_access_codes_person_idx on public.portal_access_codes(tenant_id,person_id,created_at desc);
create index if not exists portal_access_codes_branch_idx on public.portal_access_codes(tenant_id,branch_id,created_at desc);

alter table public.portal_access_codes enable row level security;
revoke all on public.portal_access_codes from public,anon,authenticated;
grant all on public.portal_access_codes to service_role;
grant usage,select on sequence public.portal_access_codes_id_seq to service_role;

create or replace function public.resolve_portal_operator_membership_v1(
  p_identity_id uuid,p_tenant_id bigint,p_branch_id bigint
) returns bigint
language plpgsql stable set search_path to pg_catalog,extensions
as $fn$
declare v_membership bigint;begin
  select m.id into v_membership
  from public.memberships m
  where m.tenant_id=p_tenant_id and m.identity_id=p_identity_id and m.status='active'
    and (m.starts_at is null or m.starts_at<=now()) and (m.ends_at is null or m.ends_at>now())
    and (m.all_branches or exists(select 1 from public.membership_branch_scopes s where s.tenant_id=m.tenant_id and s.membership_id=m.id and s.branch_id=p_branch_id))
    and exists(
      select 1 from public.membership_roles mr
      join public.roles r on r.tenant_id=mr.tenant_id and r.id=mr.role_id and r.status='active'
      join public.role_permissions rp on rp.tenant_id=r.tenant_id and rp.role_id=r.id
      where mr.tenant_id=m.tenant_id and mr.membership_id=m.id and rp.permission_code='portal.notice.manage'
    )
  order by m.created_at limit 1;
  return v_membership;
end;$fn$;

create or replace function public.get_portal_operator_center_v1(
  p_identity_id uuid,p_tenant_id bigint,p_branch_id bigint
) returns jsonb
language plpgsql stable set search_path to pg_catalog,extensions
as $fn$
declare v_membership bigint;v_guardians jsonb;v_employees jsonb;v_codes jsonb;v_notices jsonb;begin
  v_membership:=public.resolve_portal_operator_membership_v1(p_identity_id,p_tenant_id,p_branch_id);
  if v_membership is null then raise exception 'portal administration permission denied';end if;

  select coalesce(jsonb_agg(row_to_json(x) order by x.display_name,x.person_id),'[]'::jsonb) into v_guardians from(
    select distinct gp.person_id,p.display_name,gp.portal_invitation_status,
      exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.person_id=gp.person_id and l.link_type='guardian' and l.status='verified') linked,
      (select max(c.created_at) from public.portal_access_codes c where c.tenant_id=p_tenant_id and c.person_id=gp.person_id and c.link_type='guardian') last_code_at
    from public.guardian_profiles gp
    join public.persons p on p.tenant_id=gp.tenant_id and p.id=gp.person_id
    join public.person_relationships pr on pr.tenant_id=gp.tenant_id and pr.source_person_id=gp.person_id and pr.status='verified' and pr.portal_visibility in('limited','standard')
    join public.enrollments e on e.tenant_id=pr.tenant_id and e.student_person_id=pr.target_person_id and e.branch_id=p_branch_id and e.status in('active','paused')
    where gp.tenant_id=p_tenant_id and p.status='active'
  )x;

  select coalesce(jsonb_agg(row_to_json(x) order by x.display_name,x.person_id),'[]'::jsonb) into v_employees from(
    select distinct he.employee_person_id person_id,p.display_name,he.employee_number,he.designation_key,he.state,
      exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.person_id=he.employee_person_id and l.link_type='employee' and l.status='verified') linked,
      (select max(c.created_at) from public.portal_access_codes c where c.tenant_id=p_tenant_id and c.person_id=he.employee_person_id and c.link_type='employee') last_code_at
    from public.hr_employments he join public.persons p on p.tenant_id=he.tenant_id and p.id=he.employee_person_id
    where he.tenant_id=p_tenant_id and he.branch_id=p_branch_id and he.state in('active','on_leave') and p.status='active'
  )x;

  select coalesce(jsonb_agg(row_to_json(x) order by x.created_at desc,x.id desc),'[]'::jsonb) into v_codes from(
    select c.id,c.person_id,c.link_type,c.state,c.expires_at,c.claimed_at,c.created_at,p.display_name
    from public.portal_access_codes c join public.persons p on p.tenant_id=c.tenant_id and p.id=c.person_id
    where c.tenant_id=p_tenant_id and c.branch_id=p_branch_id order by c.created_at desc,c.id desc limit 30
  )x;

  select coalesce(jsonb_agg(row_to_json(x) order by x.created_at desc,x.id desc),'[]'::jsonb) into v_notices from(
    select n.id,n.audience_type,n.audience_key,n.labels,n.body,n.state,n.published_at,n.expires_at,n.created_at
    from public.portal_notices n where n.tenant_id=p_tenant_id and (n.branch_id is null or n.branch_id=p_branch_id)
    order by n.created_at desc,n.id desc limit 30
  )x;

  return jsonb_build_object('guardians',v_guardians,'employees',v_employees,'access_codes',v_codes,'notices',v_notices);
end;$fn$;

create or replace function public.issue_portal_access_code_v1(
  p_identity_id uuid,p_tenant_id bigint,p_branch_id bigint,p_person_id bigint,p_link_type text,p_token_digest text,p_expires_at timestamptz
) returns jsonb
language plpgsql set search_path to pg_catalog,extensions
as $fn$
declare v_membership bigint;v_link_type text:=lower(btrim(coalesce(p_link_type,'')));v_id bigint;begin
  v_membership:=public.resolve_portal_operator_membership_v1(p_identity_id,p_tenant_id,p_branch_id);
  if v_membership is null then raise exception 'portal administration permission denied';end if;
  if v_link_type not in('guardian','employee') then raise exception 'portal link type must be guardian or employee';end if;
  if p_token_digest is null or p_token_digest !~ '^[a-f0-9]{64}$' then raise exception 'valid portal token digest required';end if;
  if p_expires_at is null or p_expires_at<=now() or p_expires_at>now()+interval '30 days' then raise exception 'portal access code expiry must be within 30 days';end if;
  if not exists(select 1 from public.branches b where b.tenant_id=p_tenant_id and b.id=p_branch_id and b.status='active') then raise exception 'active branch required';end if;

  if v_link_type='guardian' then
    if not exists(
      select 1 from public.guardian_profiles gp
      join public.person_relationships pr on pr.tenant_id=gp.tenant_id and pr.source_person_id=gp.person_id and pr.status='verified' and pr.portal_visibility in('limited','standard')
      join public.enrollments e on e.tenant_id=pr.tenant_id and e.student_person_id=pr.target_person_id and e.branch_id=p_branch_id and e.status in('active','paused')
      where gp.tenant_id=p_tenant_id and gp.person_id=p_person_id
    ) then raise exception 'guardian is not portal-eligible in this branch';end if;
  else
    if not exists(select 1 from public.hr_employments he where he.tenant_id=p_tenant_id and he.branch_id=p_branch_id and he.employee_person_id=p_person_id and he.state in('active','on_leave')) then raise exception 'employee is not portal-eligible in this branch';end if;
  end if;

  update public.portal_access_codes set state='revoked',updated_at=now()
  where tenant_id=p_tenant_id and person_id=p_person_id and link_type=v_link_type and state='issued';

  insert into public.portal_access_codes(tenant_id,branch_id,person_id,link_type,token_digest,state,expires_at,issued_by_membership_id)
  values(p_tenant_id,p_branch_id,p_person_id,v_link_type,p_token_digest,'issued',p_expires_at,v_membership) returning id into v_id;

  if v_link_type='guardian' then update public.guardian_profiles set portal_invitation_status='invited',updated_at=now() where tenant_id=p_tenant_id and person_id=p_person_id;end if;

  insert into public.audit_events(tenant_id,branch_id,actor_identity_id,actor_membership_id,action,outcome,entity_type,entity_id,correlation_id,after_state)
  values(p_tenant_id,p_branch_id,p_identity_id,v_membership,'portal.access.issue','succeeded','portal_access_code',v_id::text,gen_random_uuid(),jsonb_build_object('person_id',p_person_id,'link_type',v_link_type,'expires_at',p_expires_at));
  return jsonb_build_object('access_code_id',v_id,'state','issued','expires_at',p_expires_at);
end;$fn$;

create or replace function public.claim_portal_access_code_v1(
  p_identity_id uuid,p_token_digest text
) returns jsonb
language plpgsql set search_path to pg_catalog,extensions
as $fn$
declare v_code public.portal_access_codes%rowtype;begin
  if p_identity_id is null then raise exception 'authenticated identity required';end if;
  if p_token_digest is null or p_token_digest !~ '^[a-f0-9]{64}$' then raise exception 'valid portal token digest required';end if;
  select * into v_code from public.portal_access_codes c where c.token_digest=p_token_digest for update;
  if v_code.id is null then raise exception 'portal access code not found';end if;
  if v_code.state<>'issued' then raise exception 'portal access code is no longer available';end if;
  if v_code.expires_at<=now() then update public.portal_access_codes set state='expired',updated_at=now() where id=v_code.id;raise exception 'portal access code expired';end if;
  if not exists(select 1 from auth.users u where u.id=p_identity_id) then raise exception 'authenticated identity not found';end if;
  if exists(select 1 from public.identity_person_links l where l.tenant_id=v_code.tenant_id and l.identity_id=p_identity_id and l.status='verified' and l.person_id<>v_code.person_id) then raise exception 'identity is already linked to another person in this institution';end if;

  insert into public.identity_person_links(tenant_id,identity_id,person_id,link_type,status,verified_at,verified_by_membership_id)
  values(v_code.tenant_id,p_identity_id,v_code.person_id,v_code.link_type,'verified',now(),v_code.issued_by_membership_id)
  on conflict(tenant_id,identity_id,person_id,link_type) do update set status='verified',verified_at=excluded.verified_at,verified_by_membership_id=excluded.verified_by_membership_id,updated_at=now();

  update public.portal_access_codes set state='claimed',claimed_identity_id=p_identity_id,claimed_at=now(),updated_at=now() where id=v_code.id;
  if v_code.link_type='guardian' then update public.guardian_profiles set portal_invitation_status='active',updated_at=now() where tenant_id=v_code.tenant_id and person_id=v_code.person_id;end if;

  return jsonb_build_object('tenant_id',v_code.tenant_id,'branch_id',v_code.branch_id,'person_id',v_code.person_id,'link_type',v_code.link_type,'state','claimed');
end;$fn$;

create or replace function public.get_portal_home_v1(
  p_identity_id uuid,p_tenant_id bigint
) returns jsonb
language plpgsql stable set search_path to pg_catalog,extensions
as $fn$
declare v_links jsonb;v_children jsonb;v_employee jsonb;v_notices jsonb;v_has_guardian boolean;v_has_employee boolean;begin
  if not exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified') then raise exception 'verified portal link required';end if;
  select exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='guardian' and l.status='verified') into v_has_guardian;
  select exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='employee' and l.status='verified') into v_has_employee;

  select coalesce(jsonb_agg(row_to_json(x) order by x.link_type,x.display_name),'[]'::jsonb) into v_links from(
    select l.person_id,l.link_type,p.display_name,p.name_native,p.preferred_locale
    from public.identity_person_links l join public.persons p on p.tenant_id=l.tenant_id and p.id=l.person_id
    where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified'
  )x;

  select coalesce(jsonb_agg(row_to_json(x) order by x.display_name),'[]'::jsonb) into v_children from(
    select sp.person_id,sp.student_number,p.display_name,p.name_native,e.branch_id,e.session_id,e.group_id,e.status enrollment_status,
      (select count(*)::int from public.attendance_records ar join public.attendance_sessions ats on ats.tenant_id=ar.tenant_id and ats.id=ar.attendance_session_id where ar.tenant_id=p_tenant_id and ar.person_id=sp.person_id and ats.attendance_date>=current_date-30) attendance_total_30d,
      (select count(*)::int from public.attendance_records ar join public.attendance_sessions ats on ats.tenant_id=ar.tenant_id and ats.id=ar.attendance_session_id where ar.tenant_id=p_tenant_id and ar.person_id=sp.person_id and ats.attendance_date>=current_date-30 and ar.status_category='present') attendance_present_30d,
      (select row_to_json(q) from(select ra.occurred_at,ra.work_category,ra.overall_score,ra.outcome,ra.parent_visible_remark from public.recitation_attempts ra where ra.tenant_id=p_tenant_id and ra.student_person_id=sp.person_id order by ra.occurred_at desc,ra.id desc limit 1)q) latest_quran
    from public.identity_person_links l
    join public.person_relationships pr on pr.tenant_id=l.tenant_id and pr.source_person_id=l.person_id and pr.status='verified' and pr.portal_visibility in('limited','standard')
    join public.student_profiles sp on sp.tenant_id=pr.tenant_id and sp.person_id=pr.target_person_id and sp.status in('active','admitted')
    join public.persons p on p.tenant_id=sp.tenant_id and p.id=sp.person_id
    join lateral(select ee.* from public.enrollments ee where ee.tenant_id=sp.tenant_id and ee.student_person_id=sp.person_id and ee.status in('active','paused') order by ee.starts_on desc,ee.id desc limit 1)e on true
    where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='guardian' and l.status='verified'
  )x;

  select row_to_json(x) into v_employee from(
    select ep.person_id,ep.employee_number,p.display_name,ep.designation,ep.department_key,ep.employment_type,ep.joined_on,ep.status,
      (select coalesce(jsonb_agg(row_to_json(a) order by a.attendance_date desc),'[]'::jsonb) from(select har.attendance_date,har.status,har.check_in_at,har.check_out_at from public.hr_employments he join public.hr_attendance_records har on har.tenant_id=he.tenant_id and har.employment_id=he.id where he.tenant_id=p_tenant_id and he.employee_person_id=ep.person_id order by har.attendance_date desc limit 14)a) recent_attendance,
      (select coalesce(jsonb_agg(row_to_json(lr) order by lr.created_at desc),'[]'::jsonb) from(select r.starts_on,r.ends_on,r.requested_units,r.reason,r.state,r.created_at from public.hr_employments he join public.hr_leave_requests r on r.tenant_id=he.tenant_id and r.employment_id=he.id where he.tenant_id=p_tenant_id and he.employee_person_id=ep.person_id order by r.created_at desc limit 10)lr) recent_leave
    from public.identity_person_links l join public.employee_profiles ep on ep.tenant_id=l.tenant_id and ep.person_id=l.person_id join public.persons p on p.tenant_id=ep.tenant_id and p.id=ep.person_id
    where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='employee' and l.status='verified' and ep.status='active' order by l.created_at limit 1
  )x;

  select coalesce(jsonb_agg(row_to_json(x) order by x.published_at desc,x.id desc),'[]'::jsonb) into v_notices from(
    select n.id,n.audience_type,n.labels,n.body,n.published_at,n.expires_at,(r.notice_id is not null) is_read,r.read_at
    from public.portal_notices n
    left join public.portal_notice_receipts r on r.tenant_id=n.tenant_id and r.notice_id=n.id and r.identity_id=p_identity_id
    where n.tenant_id=p_tenant_id and n.state='published' and n.published_at<=now() and (n.expires_at is null or n.expires_at>now())
      and (n.audience_type='tenant' or (v_has_guardian and n.audience_type='parents') or (v_has_employee and n.audience_type='employees'))
    order by n.published_at desc,n.id desc limit 30
  )x;

  return jsonb_build_object('tenant_id',p_tenant_id,'links',v_links,'children',v_children,'employee',v_employee,'notices',v_notices);
end;$fn$;

create or replace function public.mark_portal_notice_read_v1(
  p_identity_id uuid,p_tenant_id bigint,p_notice_id bigint
) returns jsonb
language plpgsql set search_path to pg_catalog,extensions
as $fn$
declare v_has_guardian boolean;v_has_employee boolean;begin
  if not exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.status='verified') then raise exception 'verified portal link required';end if;
  select exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='guardian' and l.status='verified') into v_has_guardian;
  select exists(select 1 from public.identity_person_links l where l.tenant_id=p_tenant_id and l.identity_id=p_identity_id and l.link_type='employee' and l.status='verified') into v_has_employee;
  if not exists(select 1 from public.portal_notices n where n.tenant_id=p_tenant_id and n.id=p_notice_id and n.state='published' and n.published_at<=now() and (n.expires_at is null or n.expires_at>now()) and (n.audience_type='tenant' or (v_has_guardian and n.audience_type='parents') or (v_has_employee and n.audience_type='employees'))) then raise exception 'portal notice is unavailable';end if;
  insert into public.portal_notice_receipts(tenant_id,notice_id,identity_id,read_at) values(p_tenant_id,p_notice_id,p_identity_id,now()) on conflict(tenant_id,notice_id,identity_id) do update set read_at=excluded.read_at;
  return jsonb_build_object('notice_id',p_notice_id,'read',true);
end;$fn$;

create or replace function public.publish_portal_notice_v1(
  p_identity_id uuid,p_tenant_id bigint,p_branch_id bigint,p_audience_type text,p_labels jsonb,p_body jsonb,p_expires_at timestamptz
) returns jsonb
language plpgsql set search_path to pg_catalog,extensions
as $fn$
declare v_membership bigint;v_audience text:=lower(btrim(coalesce(p_audience_type,'')));v_id bigint;begin
  v_membership:=public.resolve_portal_operator_membership_v1(p_identity_id,p_tenant_id,p_branch_id);
  if v_membership is null then raise exception 'portal administration permission denied';end if;
  if v_audience not in('tenant','parents','employees') then raise exception 'portal notice audience must be tenant, parents, or employees';end if;
  if p_labels is null or jsonb_typeof(p_labels)<>'object' or nullif(btrim(coalesce(p_labels->>'en','')),'') is null then raise exception 'English notice title required';end if;
  if p_body is null or jsonb_typeof(p_body)<>'object' or nullif(btrim(coalesce(p_body->>'en','')),'') is null then raise exception 'English notice body required';end if;
  if p_expires_at is not null and p_expires_at<=now() then raise exception 'notice expiry must be in the future';end if;
  insert into public.portal_notices(tenant_id,branch_id,audience_type,audience_key,labels,body,state,published_at,expires_at,published_by_membership_id)
  values(p_tenant_id,p_branch_id,v_audience,null,p_labels,p_body,'published',now(),p_expires_at,v_membership) returning id into v_id;
  return jsonb_build_object('notice_id',v_id,'state','published','audience_type',v_audience);
end;$fn$;

