begin;

create table if not exists public.portal_push_deliveries (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  event_id bigint not null,
  subscription_id bigint not null,
  state text not null default 'sending'
    check (state in ('sending','delivered','failed')),
  attempt_count integer not null default 1 check (attempt_count between 0 and 3),
  last_status_code integer,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  delivered_at timestamptz,
  unique (tenant_id,id),
  unique (tenant_id,event_id,subscription_id),
  foreign key (tenant_id,event_id)
    references public.domain_notification_events(tenant_id,id) on delete cascade,
  foreign key (tenant_id,subscription_id)
    references public.portal_push_subscriptions(tenant_id,id) on delete cascade
);

alter table public.portal_push_deliveries enable row level security;
alter table public.portal_push_deliveries force row level security;
revoke all on public.portal_push_deliveries from public,anon,authenticated;
grant select,insert,update on public.portal_push_deliveries to service_role;
create index if not exists portal_push_deliveries_state_idx
  on public.portal_push_deliveries(tenant_id,state,updated_at);

create or replace function public.reserve_portal_push_delivery_v1(
  p_tenant_id bigint,
  p_event_id bigint,
  p_subscription_id bigint
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
declare
  v_row public.portal_push_deliveries%rowtype;
begin
  if not exists(
    select 1
    from public.domain_notification_events e
    where e.tenant_id=p_tenant_id and e.id=p_event_id
  ) then raise exception 'notification event unavailable'; end if;

  if not exists(
    select 1
    from public.portal_push_subscriptions s
    where s.tenant_id=p_tenant_id and s.id=p_subscription_id and s.state='active'
  ) then return jsonb_build_object('reserved',false,'reason','inactive_subscription'); end if;
  insert into public.portal_push_deliveries(
    tenant_id,event_id,subscription_id,state,attempt_count,updated_at
  ) values(
    p_tenant_id,p_event_id,p_subscription_id,'sending',1,clock_timestamp()
  )
  on conflict(tenant_id,event_id,subscription_id) do nothing
  returning * into v_row;

  if v_row.id is not null then
    return jsonb_build_object(
      'reserved',true,'delivery_id',v_row.id,'attempt_count',v_row.attempt_count
    );
  end if;

  select * into v_row
  from public.portal_push_deliveries d
  where d.tenant_id=p_tenant_id
    and d.event_id=p_event_id
    and d.subscription_id=p_subscription_id
  for update;

  if v_row.state='delivered' then
    return jsonb_build_object('reserved',false,'reason','delivered');
  end if;

  if v_row.state='sending' and v_row.updated_at>clock_timestamp()-interval '2 minutes' then
    return jsonb_build_object('reserved',false,'reason','in_flight');
  end if;
  if v_row.attempt_count>=3 then
    return jsonb_build_object('reserved',false,'reason','attempts_exhausted');
  end if;

  update public.portal_push_deliveries
  set state='sending',
      attempt_count=attempt_count+1,
      last_status_code=null,
      last_error=null,
      updated_at=clock_timestamp()
  where tenant_id=p_tenant_id and id=v_row.id
  returning * into v_row;

  return jsonb_build_object(
    'reserved',true,'delivery_id',v_row.id,'attempt_count',v_row.attempt_count
  );
end;
$fn$;

revoke all on function public.reserve_portal_push_delivery_v1(bigint,bigint,bigint)
  from public,anon,authenticated;
grant execute on function public.reserve_portal_push_delivery_v1(bigint,bigint,bigint)
  to service_role;
create or replace function public.finish_portal_push_delivery_v1(
  p_tenant_id bigint,
  p_delivery_id bigint,
  p_success boolean,
  p_status_code integer default null,
  p_error text default null
) returns jsonb
language plpgsql
security definer
set search_path to ''
as $fn$
declare
  v_row public.portal_push_deliveries%rowtype;
begin
  update public.portal_push_deliveries
  set state=case when p_success then 'delivered' else 'failed' end,
      last_status_code=p_status_code,
      last_error=case when p_success then null else left(coalesce(p_error,'push_failed'),500) end,
      delivered_at=case when p_success then clock_timestamp() else null end,
      updated_at=clock_timestamp()
  where tenant_id=p_tenant_id and id=p_delivery_id
  returning * into v_row;

  if v_row.id is null then raise exception 'push delivery unavailable'; end if;
  return jsonb_build_object(
    'delivery_id',v_row.id,
    'state',v_row.state,
    'attempt_count',v_row.attempt_count
  );
end;
$fn$;

revoke all on function public.finish_portal_push_delivery_v1(bigint,bigint,boolean,integer,text)
  from public,anon,authenticated;
grant execute on function public.finish_portal_push_delivery_v1(bigint,bigint,boolean,integer,text)
  to service_role;

commit;
