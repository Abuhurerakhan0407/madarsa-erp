create table if not exists public.public_admission_photo_uploads (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  token_digest text not null unique,
  storage_path text not null unique,
  content_type text not null,
  size_bytes bigint not null,
  expires_at timestamptz not null,
  application_id bigint null references public.applications(id) on delete cascade,
  consumed_at timestamptz null,
  created_at timestamptz not null default now(),
  constraint public_admission_photo_uploads_token_digest_check check (token_digest ~ '^[0-9a-f]{64}$'),
  constraint public_admission_photo_uploads_content_type_check check (content_type in ('image/jpeg','image/png','image/webp')),
  constraint public_admission_photo_uploads_size_check check (size_bytes between 1 and 5242880),
  constraint public_admission_photo_uploads_path_check check (storage_path ~ '^[0-9]+/admissions/intake/[a-zA-Z0-9._-]+$')
);

create index if not exists public_admission_photo_uploads_tenant_expiry_idx
  on public.public_admission_photo_uploads (tenant_id, expires_at)
  where consumed_at is null;

